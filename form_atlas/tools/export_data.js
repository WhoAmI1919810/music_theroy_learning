#!/usr/bin/env node
"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const read = (file) => JSON.parse(fs.readFileSync(path.join(ROOT, file), "utf8").replace(/^\uFEFF/, ""));

const bookPayload = read("corpus/books.json");
const theory = read("evidence/theory.json");
const sourceMap = read("evidence/source-map.json");
const casePayload = read("evidence/cases.json");

const books = bookPayload.books;
const bookIds = new Set(books.map((book) => book.id));
const claims = sourceMap.claims;
const cases = casePayload.cases;

function fail(message) {
  console.error("form data error: " + message);
  process.exit(1);
}

for (const claim of claims) {
  if (!claim.id || !claim.topic || !claim.statement) fail("incomplete claim " + (claim.id || "(unknown)"));
  if (!Array.isArray(claim.books) || claim.books.length < 2) fail("claim needs at least two textbook sources: " + claim.id);
  for (const source of claim.books) {
    if (!bookIds.has(source.book)) fail("claim " + claim.id + " cites unknown book " + source.book);
    if (!Number.isInteger(source.page) || source.page < 1) fail("claim " + claim.id + " has invalid page");
    if (!source.quote || !source.quote.trim()) fail("claim " + claim.id + " has no quote");
    source.ref = "ref-" + claim.id.replace(/[^0-9A-Za-z_-]+/g, "-").toLowerCase() +
      "-p" + String(source.page).padStart(4, "0");
  }
}

const citedBooks = new Set(claims.flatMap((claim) => claim.books.map((source) => source.book)));
for (const book of books) {
  if (!citedBooks.has(book.id)) fail("book is not used by any claim: " + book.id);
}

const claimIds = new Set(claims.map((claim) => claim.id));
const caseIds = new Set(cases.map((item) => item.id));
const formIds = new Set(theory.forms.map((form) => form.id));
for (const form of theory.forms) {
  for (const claimId of form.claims || []) if (!claimIds.has(claimId)) fail("form " + form.id + " references missing claim " + claimId);
  for (const caseId of form.cases || []) if (!caseIds.has(caseId)) fail("form " + form.id + " references missing case " + caseId);
}
for (const item of cases) {
  if (!formIds.has(item.form)) fail("case " + item.id + " references missing form " + item.form);
  if (!item.sources || !item.sources.length) fail("case has no source: " + item.id);
  for (const source of item.sources) {
    if (!bookIds.has(source.book)) fail("case " + item.id + " cites unknown book " + source.book);
    if (!Number.isInteger(source.page) || source.page < 1) fail("case " + item.id + " has invalid page");
  }
  for (const claimId of item.relatedClaims || []) if (!claimIds.has(claimId)) fail("case " + item.id + " references missing claim " + claimId);
}

const payload = {
  version: theory.version,
  books,
  layers: theory.layers,
  nodes: theory.nodes,
  edges: theory.edges,
  principles: theory.principles,
  forms: theory.forms,
  cases,
  claims,
  analysisSteps: theory.analysisSteps,
  coverageTopics: theory.coverageTopics
};

const banner = "/* Generated by tools/export_data.js. Edit JSON evidence files, not this file. */\n";
const body = "(function(root){root.FORM_ATLAS=" + JSON.stringify(payload) +
  ";if(typeof module==='object'&&module.exports)module.exports=root.FORM_ATLAS;})(typeof globalThis!=='undefined'?globalThis:this);\n";
fs.writeFileSync(path.join(ROOT, "app", "data", "theory-data.js"), banner + body);
fs.writeFileSync(path.join(ROOT, "evidence", "public-data.json"), JSON.stringify(payload, null, 2) + "\n");
console.log("exported " + books.length + " books, " + claims.length + " claims, " + theory.forms.length + " forms, " + cases.length + " cases");
