"""Export compact source links for the browser application."""

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def main():
    books = json.loads((ROOT / "corpus" / "books.json").read_text(encoding="utf-8"))
    sources = json.loads((ROOT / "evidence" / "sources.json").read_text(encoding="utf-8"))
    by_id = {book["id"]: book for book in books["books"]}

    links = {}
    for claim in sources["claims"]:
        links[claim["id"]] = {
            "title": claim["title"],
            "manualAnchor": claim["manualAnchor"],
            "citations": [
                {
                    "bookId": citation["bookId"],
                    "bookTitle": by_id[citation["bookId"]]["title"],
                    "author": by_id[citation["bookId"]]["author"],
                    "pdfPage": citation["pdfPage"],
                    "printedPage": citation.get("printedPage"),
                    "chapter": citation.get("chapter", ""),
                    "quote": citation.get("quote", ""),
                    "href": "../docs/books/%s.html#claim-%s"
                    % (citation["bookId"], claim["id"]),
                }
                for citation in claim["citations"]
            ],
        }

    output = (
        "/* Generated by tools/build_app_evidence.py. */\n"
        "(function (root) {\n"
        '  "use strict";\n'
        "  const links = "
        + json.dumps(links, ensure_ascii=False, indent=2)
        + ";\n"
        "  if (typeof module !== \"undefined\" && module.exports) module.exports = links;\n"
        "  root.CP_EVIDENCE = links;\n"
        "})(typeof window !== \"undefined\" ? window : globalThis);\n"
    )
    target = ROOT / "app" / "data" / "evidence-links.js"
    target.write_text(output, encoding="utf-8")
    print("claims:", len(links))


if __name__ == "__main__":
    main()
